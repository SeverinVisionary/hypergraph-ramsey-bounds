    solve_s = time.time() - t1

    verified = None
    if sat:
        nv = comb(n, k)
        chi_perm = [0] * nv
        for lit in model:
            v = abs(lit)
            if 1 <= v <= nv:
                chi_perm[v - 1] = 1 if lit > 0 else 0
