"""Measured cost calibration for the R(s,t;k) witness search.

Two rules this file is written to obey:

  - Back-test the model against ground truth already held, before quoting any
    projection. Ground truth here is the completed R(4,4;3) bracket.
  - Quote the scaling law with the number. A headline figure without its growth
    exponent underestimated one range in this repo by ~2600x.
  - Calibrate with REPEATS; publish the spread; discard contaminated points.
    Where spread exceeds the effect, the figure is a LOWER BOUND -- say so.
  - Never apply an unmeasured speedup. Compute rather than eyeball.

Spread is generated by relabelling vertices with a random permutation before
building the CNF. That yields isomorphic instances -- same answer, same size,
genuinely different clause and variable order -- so the spread measured is the
solver's real sensitivity, not noise from a different problem.

Each instance runs in its own process with a hard wall-clock cap, so a hang
costs the cap and not the run.
"""

from __future__ import annotations

import argparse
import json
import sys
import multiprocessing as mp
import platform
import random
import statistics
import time
from itertools import combinations
from math import comb

from pysat.formula import CNF
from pysat.solvers import Cadical195

from capped import run_in_child
from verify import verify_both


def build_cnf_permuted(n, s, t, k, seed):
    """CNF for (n,s,t,k) with vertices relabelled by a seeded permutation.

    Isomorphic to the unpermuted instance: same variable count, same clause
    count, same satisfiability. Only the ordering differs, which is exactly the
    axis a CDCL solver is sensitive to.
    """
    rng = random.Random(seed)
    perm = list(range(n))
    rng.shuffle(perm)
    index = {sub: i + 1 for i, sub in enumerate(combinations(range(n), k))}

    def rank_of(vertices):
        return index[tuple(sorted(perm[v] for v in vertices))]

    cnf = CNF()
    for clique in combinations(range(n), s):
        cnf.append([rank_of(sub) for sub in combinations(clique, k)])
    for clique in combinations(range(n), t):
        cnf.append([-rank_of(sub) for sub in combinations(clique, k)])
    assert len(cnf.clauses) == comb(n, s) + comb(n, t)
    return cnf, perm, index


def _run_one_returning(n, s, t, k, seed):
    """The work of one calibration point, returning its record.

    Split out of `_run_one` so the supervisor in `capped.run_in_child` owns the
    queue: a child that raises now reports ERROR through the supervisor instead
    of exiting silently and hanging the parent on an unbounded `q.get()`.
    """
    t0 = time.time()
    cnf, perm, index = build_cnf_permuted(n, s, t, k, seed)
    build_s = time.time() - t0
    t1 = time.time()
    with Cadical195(bootstrap_with=cnf) as solver:
        sat = solver.solve()
        model = solver.get_model() if sat else None
    solve_s = time.time() - t1

    verified = None
    if sat:
        nv = comb(n, k)
        chi_perm = [0] * nv
        for lit in model:
            v = abs(lit)
            if 1 <= v <= nv:
                chi_perm[v - 1] = 1 if lit > 0 else 0
        # The model is in permuted coordinates; the verifier re-derives the
        # property directly on them, which is valid because a relabelling of
        # vertices maps witnesses to witnesses.
        verified = verify_both(n, s, t, k, chi_perm)
    return {
        "n": n, "s": s, "t": t, "k": k, "seed": seed,
        "status": "SAT" if sat else "UNSAT",
        "build_s": build_s, "solve_s": solve_s,
        "vars": comb(n, k), "clauses": comb(n, s) + comb(n, t),
        "verified": verified,
    }


def _run_one(n, s, t, k, seed, q):
    t0 = time.time()
    cnf, perm, index = build_cnf_permuted(n, s, t, k, seed)
