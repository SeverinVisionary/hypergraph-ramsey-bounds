def rebuild(n=N, subgroup=None, table=None):
    """Regenerate the colouring of all C(n,3) triples from TABLE alone."""
    subgroup = SUBGROUP if subgroup is None else subgroup
    table = TABLE if table is None else table
    chi = {}
    for rep, colour in table.items():
        stack = [rep]
        while stack:
            t = stack.pop()
            if t in chi:
                continue
            chi[t] = colour
            for u in subgroup:
                img = tuple(sorted((u * v) % n for v in t))
                if img not in chi:
                    stack.append(img)
            sh = tuple(sorted((v + 1) % n for v in t))
            if sh not in chi:
                stack.append(sh)
    return chi


def verify(chi=None, n=N):
    """Return (mono K_4 in colour 0, mono K_6 in colour 1)."""
    chi = rebuild() if chi is None else chi
    bad4 = 0
    for a in range(n):
        for b in range(a + 1, n):
            for c in range(b + 1, n):
                if chi[(a, b, c)]:
                    continue
                for d in range(c + 1, n):
                    if not (chi[(a, b, d)] or chi[(a, c, d)] or chi[(b, c, d)]):
                        bad4 += 1
    bad6 = 0
    for a in range(n):
        for b in range(a + 1, n):
            for c in range(b + 1, n):
                if not chi[(a, b, c)]:
                    continue
                for d in range(c + 1, n):
                    if not (chi[(a, b, d)] and chi[(a, c, d)] and chi[(b, c, d)]):
                        continue
                    for e in range(d + 1, n):
                        if not all(chi[t] for t in ((a, b, e), (a, c, e), (a, d, e),
                                                    (b, c, e), (b, d, e), (c, d, e))):
                            continue
                        for f in range(e + 1, n):
                            if all(chi[t] for t in (
                                    (a, b, f), (a, c, f), (a, d, f), (a, e, f),
                                    (b, c, f), (b, d, f), (b, e, f),
                                    (c, d, f), (c, e, f), (d, e, f))):
                                bad6 += 1
    return bad4, bad6


