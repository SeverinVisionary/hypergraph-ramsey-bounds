"""The R(4,6;3) >= 64 construction, stated as mathematics rather than output.

Companion to `construction.py`, which does the same for the 83-point
`R(4,4,4;3)` object. The witness file holds 39,711 bits; the object is 120
numbers.

THE CONSTRUCTION. Let H be the subgroup of Z_63^* generated by
{10, 19, 37, 46, 55}, of order 6, and let

    G = { x -> u*x + b : u in H, b in Z_63 },   |G| = 378.

G acts on the C(63,3) = 39,711 triples of Z_63 with exactly 120 orbits. Unlike
the 83-point case the action is NOT free: its orbit sizes are 378, 189, 126,
63 and 21. The short orbits arise from nontrivial setwise stabilisers in the
full affine group, which need not consist of pure multipliers. The displayed
orbit-colour assignment gives colour-class sizes 14,070 and 25,641; these
sizes are properties of this assignment, not consequences of nonfreeness
alone. Regularity only forces each class to be a multiple of the orbit size,
and enumerating all invariant good colourings of that class gives 36, of which
twenty-four are unbalanced. See `construction.py`, which states the same
correction.

TABLE below maps each orbit representative to its colour. Colour 0 avoids
K_4^(3); colour 1 avoids K_6^(3).

THEOREM. No 4-subset of Z_63 has all four triples colour 0, and no 6-subset has
all twenty triples colour 1. Hence R(4,6;3) >= 64.
"""

